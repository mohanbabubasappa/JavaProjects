package com.basics;

public class Concatenation {

	public static void main(String[] args) {
		String str1="mohan";
		String str2="babu";

		int a=10;
		int b=20;
		
		System.out.println(str1+str2);
		System.out.println(a+b);
		System.out.println(a+b+str1+str2);
		System.out.println(str1+str2+a+b);
	}

}
