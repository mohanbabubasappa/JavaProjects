package com.strings;

public class Concatenation {

	public static void main(String[] args) {

		String a = "Hello";
		String b = "World";
		String combined = a + ", " + b + "!";

		System.out.println(combined);          // Hello, World!
		System.out.println("x = " + 10);      // x = 10
		System.out.println("5 + 3 = " + (5+3)); // 5 + 3 = 8
		System.out.println(5+3+"mohan"); 
	}

}
