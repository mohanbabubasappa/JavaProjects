package com.basics;

public class Switch {
		public static void main(String[] args) {
			int day=7;		
			switch(day){
			case 7:
				System.out.println("Holiday");
			case 6:
				System.out.println("Saturday");
			case 5:
				System.out.println("Friday");
			case 4:
				System.out.println("Thursday");
			default:
				System.out.println("Monay or Tuesday");
		}
	}
}
